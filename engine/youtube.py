def update_channel():
    yt = youtube()
    ch = yt.channels().list(part="brandingSettings", mine=True).execute()["items"][0]
    b = ch["brandingSettings"]; c = b.setdefault("channel", {})
    c.update(description=CHANNEL["description"], keywords=CHANNEL["keywords"], defaultLanguage="en")
    yt.channels().update(part="brandingSettings", body={"id": ch["id"], "brandingSettings": b}).execute()
    return ch["id"]

def set_banner(path):
    yt = youtube()
    url = yt.channelBanners().insert(media_body=MediaFileUpload(str(path), mimetype="image/jpeg")).execute()["url"]
    ch = yt.channels().list(part="brandingSettings", mine=True).execute()["items"][0]
    b = ch["brandingSettings"]; b.setdefault("image", {})["bannerExternalUrl"] = url
    yt.channels().update(part="brandingSettings", body={"id": ch["id"], "brandingSettings": b}).execute()

def upload(video, title, description, tags, privacy="public", category="27", publish_at=None):
    """publish_at: ISO 8601 UTC ("2026-11-20T15:00:00Z") -> uploaded as private and released by YouTube at that time."""
    yt = youtube()
    body = {"snippet": {"title": title, "description": description, "tags": tags, "categoryId": category,
                        "defaultLanguage": "en", "defaultAudioLanguage": "en"},
            "status": {"privacyStatus": privacy, "selfDeclaredMadeForKids": False, "embeddable": True,
                       "license": "youtube", "publicStatsViewable": True, "containsSyntheticMedia": False}}
    if publish_at: body["status"].update(privacyStatus="private", publishAt=publish_at)
    req = yt.videos().insert(part="snippet,status", body=body,
                             media_body=MediaFileUpload(str(video), chunksize=16 * 1024 * 1024, resumable=True))
    resp = None
    while resp is None:
        st, resp = req.next_chunk()
        if st: print(f"  upload {st.progress() * 100:.0f}%", flush=True)
    return resp["id"]

def set_thumbnail(vid, path):
    youtube().thumbnails().set(videoId=vid, media_body=MediaFileUpload(str(path), mimetype="image/png")).execute()

def add_captions(vid, srt, lang="en", name="English"):
    youtube().captions().insert(part="snippet", body={"snippet": {"videoId": vid, "language": lang, "name": name,
                                "isDraft": False}}, media_body=MediaFileUpload(str(srt), mimetype="application/octet-stream")).execute()
